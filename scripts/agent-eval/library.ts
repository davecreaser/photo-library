// The eval library (spec 0010, AC-2): a generated photo folder, the template app data the app makes
// from it, the people and albums seeded into it, and the ground truth the graders compare with.
// Generated images only; the names are placeholders.
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { colourPhoto, photo, scenePhoto } from '../../e2e/library.ts'
import type { Truth } from './tasks.ts'

export const GENERATOR_VERSION = 1
export const MANIFEST = 'eval-library.json'
const ROOT = join(import.meta.dirname, '..', '..')

/** What the cache depends on: the generator and the app's analysis and schema versions (AC-2). */
export function cacheKey(): string {
  const read = (p: string) => readFileSync(join(ROOT, p), 'utf8')
  const grab = (file: string, name: string) => read(file).match(new RegExp(`${name} = (\\d+)`))?.[1] ?? '?'
  const parts = [
    `generator ${GENERATOR_VERSION} ${createHash('sha256').update(read('scripts/agent-eval/library.ts')).digest('hex').slice(0, 12)}`,
    `schema ${grab('src/main/db.ts', 'SCHEMA_VERSION')}`,
    `content ${grab('src/main/contentModel.ts', 'CONTENT_MODEL_VERSION')}`,
    `face ${grab('src/main/faces.ts', 'FACE_MODEL_VERSION')}`,
    `quality ${grab('src/main/quality.ts', 'QUALITY_VERSION')}`
  ]
  return parts.join(', ')
}

const exif = (y: number, m: number, d: number, h: number, min: number) =>
  `${y}:${String(m).padStart(2, '0')}:${String(d).padStart(2, '0')} ${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}:00`

/**
 * A trip folder: `scenes` look-alike scenes of 5 shots a minute apart, then `singles` one-off
 * scenes, spread over the days from `start`, at least two hours apart.
 */
async function trip(dir: string, firstScene: number, scenes: number, singles: number, y: number, m: number, d: number, days: number): Promise<void> {
  const slots = scenes + singles
  for (let i = 0; i < slots; i++) {
    const day = d + Math.floor((i * days) / slots)
    const hour = 8 + ((i * 2) % 12)
    if (i < scenes) {
      for (let s = 0; s < 5; s++) await scenePhoto(join(dir, `S${i}_${s}.JPG`), firstScene + i, s * 2, exif(y, m, day, hour, s), `eval ${firstScene + i}.${s}`)
    } else await scenePhoto(join(dir, `IMG_${i - scenes}.JPG`), firstScene + i, 0, exif(y, m, day, hour, 0), `eval single ${firstScene + i}`)
  }
}

/** Builds the photo folder (about 570 generated JPEGs) and its manifest. */
export async function generate(root: string): Promise<void> {
  await trip(join(root, 'trips', 'norway_2024'), 1, 8, 20, 2024, 8, 5, 5)
  await trip(join(root, 'trips', 'sintra_2026'), 100, 4, 10, 2026, 9, 12, 4)
  await trip(join(root, 'trips', 'lisbon_2026'), 200, 0, 10, 2026, 5, 3, 3)
  await trip(join(root, 'trips', 'poland_2022'), 300, 0, 12, 2022, 6, 14, 4)
  await trip(join(root, 'trips', 'poland_2024'), 400, 0, 12, 2024, 6, 10, 4)
  await trip(join(root, '2024', 'beach_day'), 500, 0, 20, 2024, 7, 20, 1)
  await trip(join(root, '2025', 'beach'), 600, 0, 15, 2025, 7, 12, 2)
  const colours: [string, string, number][] = [
    ['R', '#d42020', 2025],
    ['B', '#2040d4', 2025],
    ['G', '#30a040', 2025]
  ]
  for (const [c, fill, y] of colours)
    for (let i = 0; i < 10; i++) await colourPhoto(join(root, String(y), 'camera', `DSC_${c}${i}.JPG`), fill, exif(y, 2 + i, 3 + i, 10, 0))
  for (let i = 0; i < 3; i++) await colourPhoto(join(root, '2024', 'camera', `DSC_R${i}.JPG`), '#d42020', exif(2024, 4, 2 + i, 10, 0))
  // Loose 2024 photos outside the trips' months, and loose 2026 ones before Lisbon.
  const looseMonths = [1, 2, 3, 9, 10, 11, 12]
  for (let i = 0; i < 320; i++) await photo(join(root, '2024', 'camera', `IMG_${i}.JPG`), exif(2024, looseMonths[i % 7], 1 + (i % 27), 9 + (i % 10), i % 60))
  for (let i = 0; i < 40; i++) await photo(join(root, '2026', 'camera', `IMG_${i}.JPG`), exif(2026, 1 + (i % 4), 1 + (i % 27), 12, i % 60))
  for (let i = 0; i < 10; i++) await photo(join(root, 'scans', `SCAN_${i}.JPG`), null)
  for (let i = 0; i < 10; i++) await photo(join(root, 'private', `IMG_${i}.JPG`), exif(2024, 5, 5, 10, i))
  writeFileSync(
    join(root, MANIFEST),
    JSON.stringify({ generator: GENERATOR_VERSION, photos: 572, note: 'Generated by scripts/agent-eval for the assistant eval. No real photos.' }, null, 2)
  )
}

export function isEvalLibrary(root: string): boolean {
  try {
    return JSON.parse(readFileSync(join(root, MANIFEST), 'utf8')).generator === GENERATOR_VERSION
  } catch {
    return false
  }
}

interface Row {
  [k: string]: unknown
}

/** Photo id of each present file, by its path relative to the photo folder ('/' separated). */
function photosByPath(db: DatabaseSync, root: string): Map<string, { id: number; takenAt: string | null }> {
  const rows = db
    .prepare('SELECT f.path, p.id, p.taken_at FROM files f JOIN photos p ON p.id = f.photo_id WHERE f.missing = 0 AND p.present = 1')
    .all() as Row[]
  return new Map(
    rows.map((r) => [
      relative(root, r.path as string)
        .split(sep)
        .join('/'),
      { id: r.id as number, takenAt: (r.taken_at as string) ?? null }
    ])
  )
}

const byName = (a: string, b: string) => a.localeCompare(b, 'en', { numeric: true })

/** Ids of the files under `prefix` (and matching `name`), in file-name order. */
function under(map: Map<string, { id: number }>, prefix: string, name = /./): number[] {
  return [...map.keys()]
    .filter((p) => p.startsWith(prefix) && name.test(p.slice(prefix.length)))
    .sort(byName)
    .map((p) => map.get(p)!.id)
}

/** Who is where (AC-2): fixed photos, so graders know the answer. */
function people(map: Map<string, { id: number }>) {
  const beach = under(map, '2024/beach_day/')
  const sintraBursts = under(map, 'trips/sintra_2026/', /^S/)
  const sintraSingles = under(map, 'trips/sintra_2026/', /^IMG/)
  return {
    alex: [...beach.slice(0, 8), ...sintraBursts.slice(0, 5), sintraSingles[0]],
    sam: [...beach.slice(6, 12), sintraBursts[10], ...sintraSingles.slice(1, 4)],
    beachWithSam: [...beach.slice(6, 16)],
    favourites: [...under(map, 'trips/norway_2024/', /^S\d_0/).slice(0, 4), ...sintraSingles.slice(4, 6), ...under(map, '2024/camera/', /^IMG/).slice(0, 14)]
  }
}

/**
 * Seeds the template with the app's own database functions, as the tests do (AC-2): Alex and Sam,
 * 20 favourites, the owner's "Sintra 2026" and "Lisbon", and the assistant album "Beach with Sam".
 * Runs while the app is closed.
 */
export async function seed(dbFile: string, root: string): Promise<void> {
  const { LibraryDb } = await import('../../src/main/db.ts')
  const { FACE_MODEL_VERSION } = await import('../../src/main/faces.ts')
  const db = new LibraryDb(dbFile)
  try {
    const raw = new DatabaseSync(dbFile, { readOnly: true })
    const map = photosByPath(raw, root)
    raw.close()
    const who = people(map)
    db.transaction(() => {
      // Generated images have no faces: one face per person per photo, named by hand as the owner
      // would. Saved per photo in one call, since saving replaces a photo's faces.
      const people = { Alex: db.personNamed('Alex'), Sam: db.personNamed('Sam') }
      const byPhoto = new Map<number, (keyof typeof people)[]>()
      for (const id of who.alex) byPhoto.set(id, [...(byPhoto.get(id) ?? []), 'Alex'])
      for (const id of who.sam) byPhoto.set(id, [...(byPhoto.get(id) ?? []), 'Sam'])
      for (const [id, names] of byPhoto) {
        const faces = db.saveFaces(
          id,
          names.map((_, k) => ({ x: 0.2 + 0.4 * k, y: 0.3, w: 0.2, h: 0.25, score: 0.95, embedding: null })),
          FACE_MODEL_VERSION
        )
        names.forEach((name, k) => db.confirmFaces([faces[k]], people[name]))
      }
      db.setFavorite(who.favourites, true)
      const sintra = db.createAlbum('Sintra 2026', null)
      db.addToAlbum(sintra.id, under(map, 'trips/sintra_2026/'))
      const lisbon = db.createAlbum('Lisbon', null)
      db.addToAlbum(lisbon.id, under(map, 'trips/lisbon_2026/'))
      db.createAssistantAlbum('Beach with Sam', who.beachWithSam)
    })
  } finally {
    db.close()
  }
}

/** The ground truth, read from the template database (read-only). */
export function truthFrom(dbFile: string, root: string): Truth {
  const db = new DatabaseSync(dbFile, { readOnly: true })
  try {
    const map = photosByPath(db, root)
    const who = people(map)
    const year = (y: string) => [...map.values()].filter((p) => p.takenAt?.startsWith(y)).map((p) => p.id)
    const scene: Record<number, string> = {}
    for (const [path, { id }] of map) {
      const m = path.match(/^trips\/(\w+?)_\d+\/S(\d+)_\d+\.JPG$/)
      if (m) scene[id] = `${m[1]}:${m[2]}`
    }
    const albumId = (name: string) => (db.prepare('SELECT id FROM albums WHERE name = ?').get(name) as Row | undefined)?.id as number
    const named = (name: string) =>
      (db.prepare('SELECT DISTINCT f.photo_id FROM faces f JOIN people p ON p.id = f.person_id WHERE p.name = ?').all(name) as Row[]).map(
        (r) => r.photo_id as number
      )
    return {
      photos: map.size,
      people: ['Alex', 'Sam'],
      norway: under(map, 'trips/norway_2024/'),
      sintra: under(map, 'trips/sintra_2026/'),
      lisbon: under(map, 'trips/lisbon_2026/'),
      poland2022: under(map, 'trips/poland_2022/'),
      poland2024: under(map, 'trips/poland_2024/'),
      beach2024: under(map, '2024/beach_day/'),
      red2025: under(map, '2025/camera/', /^DSC_R/),
      year2024: year('2024'),
      year2026: year('2026'),
      alexBeach2024: who.alex.filter((id) => under(map, '2024/beach_day/').includes(id)),
      samBeach2024: who.sam.filter((id) => under(map, '2024/beach_day/').includes(id)),
      alex: named('Alex'),
      sam: named('Sam'),
      scene,
      albums: { sintra: albumId('Sintra 2026'), lisbon: albumId('Lisbon'), beachWithSam: albumId('Beach with Sam') }
    }
  } finally {
    db.close()
  }
}

/** Every album with its photos, made_by and name (graded after the app quits; read-only). */
export function albumsIn(dbFile: string): { id: number; name: string; madeBy: string | null; photoIds: number[] }[] {
  const db = new DatabaseSync(dbFile, { readOnly: true })
  try {
    const albums = db.prepare('SELECT id, name, made_by FROM albums ORDER BY id').all() as Row[]
    const photos = db.prepare('SELECT photo_id FROM album_photos WHERE album_id = ? ORDER BY photo_id')
    return albums.map((a) => ({
      id: a.id as number,
      name: a.name as string,
      madeBy: (a.made_by as string) ?? null,
      photoIds: (photos.all(a.id as number) as Row[]).map((r) => r.photo_id as number)
    }))
  } finally {
    db.close()
  }
}

export function ensureDir(p: string): string {
  if (!existsSync(p)) mkdirSync(p, { recursive: true })
  return p
}
